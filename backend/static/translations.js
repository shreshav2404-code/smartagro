// Function to translate the page
function translatePage(lang) {
    // Save the selected language to localStorage
    localStorage.setItem('preferredLanguage', lang);
    
    // Get all elements with data-i18n attribute
    const elements = document.querySelectorAll('[data-i18n]');
    
    // Update each element with the translation
    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            // Handle different element types
            if (element.tagName === 'INPUT' && element.getAttribute('type') === 'submit') {
                element.value = translations[lang][key];
            } else if (element.tagName === 'INPUT' && element.getAttribute('placeholder')) {
                element.placeholder = translations[lang][key];
            } else {
                element.textContent = translations[lang][key];
            }
        }
    });
    
    // Update the language selector
    const languageSelector = document.getElementById('language-selector');
    if (languageSelector) {
        languageSelector.value = lang;
    }
    
    // Update the HTML lang attribute
    document.documentElement.lang = lang;
}

// Initialize translation on page load
document.addEventListener('DOMContentLoaded', function() {
    // Check if there's a saved language preference
    const savedLanguage = localStorage.getItem('preferredLanguage') || 'en';
    
    // Apply initial translation
    translations.currentLanguage = savedLanguage;
    updatePageContent();
});